"""Derive tile properties for byte values 0x80..0xFF (object references read as tiles) from measure.objref_all."""
import json
SP = '/tmp/claude-0/-home-claude/4a4b5c09-bdf2-5f61-92c2-02c1c6ac6cfd/scratchpad/'
O = {int(k): v for k, v in json.load(open(SP + 'objref.json')).items()}
DB = [1, 2, 4, 8]
CLS = {1: 0x00, 2: 0x70, 4: 0x50, 7: 0x10}
rows = []; bad = []
for V in range(0x80, 0x100):
    r = O[V]
    lv = r['leave']; leave = 0; ice = False; odd = []
    for d, x in enumerate(lv if isinstance(lv, list) else []):
        if x != 'pass': leave |= DB[d]
        if x == 'bounce': ice = True
        if x not in ('pass', 'bounce', 'stay'): odd.append((d, x))
    obs = {}
    for k, v in r['entry'].items():
        t, d = map(int, k.split(','))
        if v == 'crash': continue
        obs[(t, d)] = v in ('kill', 'pass')
    cands = [e for e in range(128) if all((not (e & (CLS[t] | DB[d]))) == p for (t, d), p in obs.items())]
    if not cands: bad.append((hex(V), 'entry')); e = 0x7F
    else: e = min(cands, key=lambda e: (bin(e).count('1'), e))
    onto = r['onto']
    slide = bool(onto) and onto[0] == 4
    if slide and len(onto) > 1 and onto[1] != 'crash': ice2 = onto[1] == 2
    else: ice2 = None
    if ice2 is not None and ice2 != ice and leave: bad.append((hex(V), 'ice?', ice, ice2))
    if ice2: ice = True
    rows.append((V, e, leave, slide, ice, len(cands), odd))
print('inconsistent:', bad)
print('ambiguous entry (several masks fit):', sum(1 for r in rows if r[5] > 1))
out = ['// Generated by verify/gen_objref.py: byte values 0x80..0xFF (object references) read as tiles, measured.',
       '// {entry mask, leave mask, slide, ice}. The arrival/stay handler of these values does nothing.',
       'static const uint8_t kRefTiles[128][4] = {']
for V, e, leave, slide, ice, n, odd in rows:
    out.append('    {0x%02X, 0x%X, %d, %d},   // %02X' % (e, leave, int(slide), int(ice), V))
out += ['};', '']
open('/home/claude/remake/src/core/stray_tables.inc', 'a').write('\n'.join(out))
print('appended kRefTiles; examples:', [(hex(r[0]), hex(r[1]), r[2], r[3], r[4]) for r in rows[:6]], [r for r in rows if r[6]][:5])
