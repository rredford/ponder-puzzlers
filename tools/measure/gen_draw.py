"""Generate src/core/draw_tables.inc: what drawing an odd tile code (34-7F) does in the original (doc 04 §4.4).
Measured, black box: the per-code write address (from scbaddr.json, found by searching RAM for the cell's
screen position after one drawn frame) and, for the program-code address of code 6E, which written x values
break code that runs every tick (crash next tick) versus code that runs every 6th tick."""
import sys, json
sys.path.insert(0, '/home/claude/verify'); sys.path.insert(0, '/home/claude/remake/tools/measure')
A = {int(k, 16): (v[0][1][0] if v[0][1] else None) for k, v in json.load(open('/tmp/claude-0/scbaddr.json')).items()}
from pokedelay import run
cls6e = [run(0x2F00, [v, 0, 75, 0]) for v in range(256)]
assert all(c in (1, 6) for c in cls6e)
# kinds: 0 no effect on play, 1 data write (repeat into the memory model), 2 code run every tick (61),
#        3 code of 6E (every tick or every 6th tick, by x value), 4 code of Chip's move (38)
DATA = {0x3F, 0x47, 0x45, 0x39, 0x3B, 0x3D, 0x44, 0x5C, 0x62, 0x64, 0x7B, 0x7D, 0x60, 0x7F}
kind = {c: (1 if c in DATA else 2 if c == 0x61 else 3 if c == 0x6E else 4 if c == 0x38 else 0) for c in range(0x34, 0x80)}
L = ['// Generated by tools/measure/gen_draw.py - drawing odd tile codes (doc 04 §4.4). Do not edit.',
     'struct OddDraw { uint16_t addr; uint8_t kind; };',
     'static const OddDraw kOddDraw[0x4C] = {']
for c in range(0x34, 0x80):
    a = A[c] or 0
    L.append('    {0x%04X, %d},  // %02X' % (a if kind[c] else 0, kind[c], c))
L.append('};')
L.append('// code 6E: written x value -> 1 = crash on the next tick, 6 = crash on the next tick that is a multiple of 6')
L.append('static const uint8_t k6EDelay[256] = {')
for i in range(0, 256, 32): L.append('    ' + ','.join(str(x) for x in cls6e[i:i + 32]) + ',')
L.append('};')
open('/home/claude/remake/src/core/draw_tables.inc', 'w').write('\n'.join(L) + '\n')
print('ok', sum(1 for v in kind.values() if v), 'codes with effect')
